public class Employee {
    public int id;
    public String name;
    public String email;
    public String department;
    public double salary;

    public Employee(int id, String name, String email, String department, double salary) {
        this.id = id;
        this.name = name;
        this.email = email;
        this.department = department;
        this.salary = salary;
    }
}
